# -*- coding: utf-8 -*-
import logging  # Импортируем стандартный модуль для логирования событий
import time  # Импортируем модуль для работы со временем (задержки)

class User:
    """
    Класс для представления пользователя системы.

    Управляет данными профиля и валидацией паролей.
    """

    def __init__(self, name: str, user_name: str, /, *, password: str) -> None:
        """
        Инициализирует объект пользователя.

        Аргументы name и user_name передаются только позиционно.
        Аргумент password передается строго по имени.
        """
        self.name = name  # Сохраняем имя пользователя в атрибут класса
        self.user_name = user_name  # Сохраняем логин (никнейм) в атрибут класса
        self.password = str(password)  # Принудительно приводим пароль к строке для безопасности

    def __str__(self) -> str:
        """
        Возвращает строковое представление объекта.
        
        Используется при вызове функции print(user).
        """
        return f"User(name={self.name}, user_name={self.user_name})"  # Возвращаем понятный текст вместо адреса памяти

    def _normalize_password(self) -> str:
        """
        Вспомогательный метод для нормализации строки пароля.
        
        Удаляет пробелы по краям и приводит все буквы к нижнему регистру.
        """
        return self.password.strip().lower()  # Вызываем методы строки и возвращаем результат

    def check_password_validity(self) -> bool:
        """
        Проверяет валидность типа данных пароля и запускает проверку его длины.
        
        Возвращает True, если пароль подходит, иначе False.
        """
        try:  # Открываем блок отслеживания потенциальных ошибок
            if not isinstance(self.password, (str, int)):  # Проверяем, является ли пароль строкой или числом
                logging.warning("Некорректный тип данных.")  # Записываем в лог предупреждение, если тип не подошел
                return False  # Выходим из метода, возвращая False
            
            logging.info("Тип данных правильный.")  # Записываем в лог, что проверка типа прошла успешно
            return self.process_password_length()  # Перенаправляем выполнение в метод проверки длины

        except Exception as e:  # Перехватываем любую непредвиденную ошибку
            logging.error(f"Произошла ошибка: {e}")  # Логируем текст возникшей ошибки
            return False  # Возвращаем False в случае сбоя
        finally:  # Этот блок выполнится всегда, независимо от ошибок или return выше
            time.sleep(1)  # Делаем паузу на 1 секунду (имитация задержки сети/базы данных)
            logging.info("Обработка запроса завершена.")  # Логируем финальный статус операции

    def process_password_length(self) -> bool:
        """
        Проверяет, соответствует ли длина пароля минимальным требованиям.
        
        Требуемая длина — не менее 8 символов после очистки от пробелов.
        """
        normalized = self._normalize_password()  # Получаем очищенный от пробелов и регистра пароль
        dlina = len(normalized)  # Считаем количество символов в полученной строке
        
        if dlina >= 8:  # Проверяем условие безопасности длины (больше или равно 8)
            logging.info("Длина нормальная, все хорошо.")  # Пишем в лог, что длина безопасна
            return True  # Возвращаем True (пароль прошел проверку)
        else:  # Если символов меньше 8
            logging.warning("С длиной что-то не так, пароль короткий.")  # Предупреждаем в логах
            return False  # Возвращаем False (пароль отклонен)


# Блок проверки работоспособности кода
if __name__ == "__main__":
    # Настраиваем формат вывода логов в консоль
    logging.basicConfig(level=logging.INFO, format='%(levelname)s: %(message)s')

    # Создаем пользователя. Заметьте: пароль мы ОБЯЗАНЫ передать по имени из-за знака '*' в __init__
    user = User("Алексей", "alex_dev", password="  MyLongPassword123  ")
    
    print(user)  # Печатаем информацию о пользователе (сработает метод __str__)
    
    # Запускаем проверку пароля и сохраняем результат (True/False)
    result = user.check_password_validity()
    
    print(f"Пароль одобрен? -> {result}")  # Выводим финальный вердикт

